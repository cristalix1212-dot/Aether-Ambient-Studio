from playwright.sync_api import sync_playwright
import time, json
with sync_playwright() as p:
    b=p.chromium.launch(headless=True,args=["--autoplay-policy=no-user-gesture-required","--mute-audio"])
    page=b.new_page(viewport={"width":1200,"height":800})
    errs=[]; page.on('pageerror',lambda e:errs.append(str(e)))
    page.goto('http://127.0.0.1:8765/index.html',wait_until='domcontentloaded')
    page.wait_for_function('window.__AETHER_READY__ === true'); page.wait_for_timeout(1500)
    page.evaluate("""() => {window.__LONG__=[]; try {new PerformanceObserver(l=>window.__LONG__.push(...l.getEntries().map(e=>e.duration))).observe({entryTypes:['longtask']})} catch(e){}}""")
    session=page.context.new_cdp_session(page)
    session.send('Emulation.setCPUThrottlingRate', {'rate': 6})
    page.evaluate('window.__AETHER__.loadProof()'); page.wait_for_timeout(300)
    t=time.time(); page.evaluate('async()=>await window.__AETHER__.play()')
    page.wait_for_timeout(6000)
    st=page.evaluate('window.__AETHER__.getState()')
    print('wall',round(time.time()-t,2),'position',round(st['position'],2),'playing',st['playing'],'eco',st['eco'],'audio',st['audioPlaying'])
    print('live',json.dumps(page.evaluate('window.__AETHER__.getLiveStats()'),ensure_ascii=False))
    print('longtasks',page.evaluate('window.__LONG__.slice(-20)'))
    print('errs',errs[-3:])
    b.close()
